import com.lifeos.app.data.api.TaskDto
import com.lifeos.app.data.api.TimelineBlockDto
import com.lifeos.app.domain.SyncMath
import kotlinx.serialization.builtins.ListSerializer
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.boolean
import kotlinx.serialization.json.double
import kotlinx.serialization.json.jsonArray
import kotlinx.serialization.json.jsonObject
import kotlinx.serialization.json.jsonPrimitive
import org.junit.Assert.assertEquals
import org.junit.Assert.assertTrue
import org.junit.Test
import java.time.Instant
import java.time.ZoneId

/**
 * The Kotlin port of the sync helpers, held to what the TypeScript actually
 * returns.
 *
 * ### Why this is a fixture and not a list of hand-written expectations
 *
 * Protocol 4 moved four display values onto the device — which task is
 * `current`, which reminders are `due`, where the now-marker cuts the timeline,
 * and `improvementPct` — so each one is now implemented twice: in TypeScript for
 * the web client, and in Kotlin here. When two implementations of "is this task
 * urgent" drift, the phone and the dashboard disagree about the user's own day,
 * and nothing fails loudly.
 *
 * `app/src/test/resources/sync-fixture.json` is generated by
 * `scripts/gen-sync-fixture.mjs`, which imports and runs the **real**
 * `packages/shared/src/sync.ts` and `xp.ts` over a table of cases and records
 * what they returned. This test reads that table and asserts the Kotlin returns
 * the same thing. So "the port matches the TypeScript" is a measurement against
 * the TypeScript's own output, rather than a claim about what someone believed
 * it did — which is the failure mode of restating expectations by hand, and the
 * reason the existing `ArtTest` approach was not good enough for sixty lines of
 * windowing arithmetic with NaN edges.
 *
 * The first eight `paceAdjustedImprovementPct` rows are the cases
 * `packages/shared/src/xp.test.ts` asserts itself, so the Kotlin is held to the
 * TypeScript's own suite as well as to its behaviour.
 *
 * ### Three JavaScript behaviours this pins deliberately
 *
 * The fixture encodes them, so the Kotlin cannot "improve" on them and drift:
 *
 *  - **`Date.parse` returns `NaN` and every comparison with `NaN` is false**, so
 *    an unparseable `currentUntil` does *not* close a window and an unparseable
 *    `currentFrom` does *not* stop one opening. The fixture says `true` for both.
 *  - **`if (task.showAt)` is a truthiness test**, so `showAt: ""` is absent
 *    rather than epoch.
 *  - **`Math.round` is `floor(x + 0.5)`** — a half goes toward positive
 *    infinity, so `-0.25` rounds to `-0.2`. `kotlin.math.round` rounds a half
 *    *away from zero* and would answer `-0.3`; the port uses
 *    `java.lang.Math.round`, and the fixture is what proves it.
 */
class SyncMathTest {

    private val json = ApiClient.json

    private val fixture: JsonObject by lazy {
        val text = javaClass.classLoader!!
            .getResourceAsStream("sync-fixture.json")!!
            .bufferedReader()
            .readText()
        json.parseToJsonElement(text).jsonObject
    }

    /**
     * The zone the fixture was generated in, not this machine's.
     *
     * Three of these helpers read the local wall clock, so asserting against the
     * fixture in a different zone would compare two different questions. The
     * generator records the zone it resolved; this reads it back.
     */
    private val zone: ZoneId by lazy {
        ZoneId.of(fixture["timezone"]!!.jsonPrimitive.content)
    }

    private val nowMs: Long by lazy {
        Instant.parse(fixture["now"]!!.jsonPrimitive.content).toEpochMilli()
    }

    private fun cases(name: String): JsonArray = fixture[name]!!.jsonArray

    @Test
    fun `the fixture is present and was generated in a named zone`() {
        // A fixture that silently failed to generate would make every assertion
        // below vacuous, so this asserts the table is really there and really
        // has cases in it.
        assertTrue("the fixture should carry cases", cases("isCurrentAt").isNotEmpty())
        assertEquals(
            "the recorded offset must match the zone the test resolves",
            fixture["utcOffsetMinutesAtNow"]!!.jsonPrimitive.double.toInt(),
            zone.rules.getOffset(Instant.ofEpochMilli(nowMs)).totalSeconds / 60,
        )
    }

    @Test
    fun `isCurrentAt matches the TypeScript on every case`() {
        for (case in cases("isCurrentAt")) {
            val obj = case.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val task = json.decodeFromJsonElement(TaskDto.serializer(), obj["task"]!!)
            val expected = obj["expected"]!!.jsonPrimitive.boolean
            assertEquals(name, expected, SyncMath.isCurrentAt(task, nowMs, zone))
        }
    }

    @Test
    fun `isReminderDueAt matches the TypeScript on every case`() {
        for (case in cases("isReminderDueAt")) {
            val obj = case.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val task = json.decodeFromJsonElement(TaskDto.serializer(), obj["task"]!!)
            val expected = obj["expected"]!!.jsonPrimitive.boolean
            assertEquals(name, expected, SyncMath.isReminderDueAt(task, nowMs, zone))
        }
    }

    @Test
    fun `dayFractionAt matches the TypeScript on every case`() {
        for (case in cases("dayFractionAt")) {
            val obj = case.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val day = LifeDayDto(
                lifeDay = "2026-10-30",
                lifeDayStart = obj["lifeDayStart"]!!.jsonPrimitive.content,
                lifeDayEnd = obj["lifeDayEnd"]!!.jsonPrimitive.content,
            )
            val expected = obj["expected"]!!.jsonPrimitive.double
            assertEquals(name, expected, SyncMath.dayFractionAt(day, nowMs, zone), 1e-12)
        }
    }

    @Test
    fun `paceAdjustedImprovementPct matches the TypeScript, rounding included`() {
        for (case in cases("paceAdjustedImprovementPct")) {
            val obj = case.jsonObject
            val today = obj["today"]!!.jsonPrimitive.double
            val yesterday = obj["yesterday"]!!.jsonPrimitive.double
            val fraction = obj["fraction"]!!.jsonPrimitive.double
            val expected = obj["expected"]!!.jsonPrimitive.double
            assertEquals(
                "paceAdjustedImprovementPct($today, $yesterday, $fraction)",
                expected,
                SyncMath.paceAdjustedImprovementPct(today, yesterday, fraction),
                // Exact: these are one-decimal values and the point of the case
                // is that the rounding rule is identical, not merely close.
                0.0,
            )
        }
    }

    @Test
    fun `improvementPct matches the TypeScript`() {
        for (case in cases("improvementPct")) {
            val obj = case.jsonObject
            val today = obj["today"]!!.jsonPrimitive.double
            val yesterday = obj["yesterday"]!!.jsonPrimitive.double
            val expected = obj["expected"]!!.jsonPrimitive.double
            assertEquals(expected, SyncMath.improvementPct(today, yesterday), 0.0)
        }
    }

    @Test
    fun `activityColor matches the shared table exactly`() {
        // Part of the contract rather than this client's palette: the server
        // colours the planned half of the ribbon and the client colours the
        // lived half, so two tables would make the same hour change colour as it
        // crossed the now-marker.
        for (case in cases("activityColor")) {
            val obj = case.jsonObject
            val activity = obj["activity"]!!.jsonPrimitive.content
            val expected = obj["expected"]!!.jsonPrimitive.content
            assertEquals(activity, expected, SyncMath.activityColor(activity))
        }
    }

    @Test
    fun `composeTimeline matches the TypeScript segment for segment`() {
        for (case in cases("composeTimeline")) {
            val obj = case.jsonObject
            val name = obj["name"]!!.jsonPrimitive.content
            val ribbon = json.decodeFromJsonElement(
                ListSerializer(RibbonSegmentDto.serializer()),
                obj["ribbon"]!!,
            )
            val lived = json.decodeFromJsonElement(
                ListSerializer(LoggedIntervalDto.serializer()),
                obj["lived"]!!,
            )
            val expected = json.decodeFromJsonElement(
                ListSerializer(TimelineBlockDto.serializer()),
                obj["expected"]!!,
            )

            val actual = SyncMath.composeTimeline(
                ribbon = ribbon,
                lived = lived,
                nowMs = nowMs,
                zone = zone,
            )

            assertEquals("$name: segment count", expected.size, actual.size)
            expected.zip(actual).forEachIndexed { index, (want, got) ->
                // Compared field by field rather than by `==`, so a failure says
                // which property of which segment diverged instead of printing
                // two long lists.
                assertEquals("$name[$index] id", want.id, got.id)
                assertEquals("$name[$index] category", want.category, got.category)
                assertEquals("$name[$index] label", want.label, got.label)
                assertEquals("$name[$index] startHour", want.startHour, got.startHour, 1e-9)
                assertEquals("$name[$index] endHour", want.endHour, got.endHour, 1e-9)
                assertEquals("$name[$index] color", want.color, got.color)
                assertEquals("$name[$index] status", want.status, got.status)
                assertEquals("$name[$index] actual", want.actual, got.actual)
            }
        }
    }

    /* ------------------------------------------------- what the fixture cannot say */

    @Test
    fun `an unlogged segment's id is formatted with a dot whatever the locale`() {
        // `unlogged-${from.toFixed(3)}` in the TypeScript. Kotlin's
        // `String.format` is locale-sensitive, so on a device set to a locale
        // that uses a comma decimal separator this id would come out as
        // "unlogged-0,000" and stop matching the dashboard's. The fixture is
        // generated in one locale and so cannot catch it; this can.
        val previous = java.util.Locale.getDefault()
        try {
            java.util.Locale.setDefault(java.util.Locale.GERMANY)
            val segments = SyncMath.composeTimeline(
                ribbon = emptyList(),
                lived = emptyList(),
                nowMs = nowMs,
                zone = zone,
            )
            val unlogged = segments.single()
            assertEquals("unlogged-0.000", unlogged.id)
            assertTrue("and it must be an unlogged segment", unlogged.status == "unlogged")
        } finally {
            java.util.Locale.setDefault(previous)
        }
    }

    @Test
    fun `the now-marker advances between ticks`() {
        // The property the whole move to client-side computation buys: the
        // marker moves with the clock rather than once per poll. Two
        // compositions a minute apart must not produce the same cut.
        val a = SyncMath.composeTimeline(emptyList(), emptyList(), nowMs, zone = zone)
        val b = SyncMath.composeTimeline(
            emptyList(),
            emptyList(),
            nowMs + 60_000,
            zone = zone,
        )
        assertTrue(
            "the unlogged tail must grow with the clock",
            b.single().endHour > a.single().endHour,
        )
    }

    @Test
    fun `an open interval is drawn up to the clock, not to its absent end`() {
        // `endedAt: null` is the running session. The server cannot send its end
        // because it has not happened; the client draws it to its own now.
        val lived = listOf(
            LoggedIntervalDto(
                id = "open",
                activity = "Deep Work",
                startedAt = "2026-10-30T08:00:00.000Z",
                endedAt = null,
            ),
        )
        val early = SyncMath.composeTimeline(emptyList(), lived, nowMs, zone = zone)
        val later = SyncMath.composeTimeline(emptyList(), lived, nowMs + 600_000, zone = zone)

        val a = early.first { it.id == "did-open" }
        val b = later.first { it.id == "did-open" }
        assertEquals("it must start where it started", a.startHour, b.startHour, 1e-9)
        assertTrue("and grow at the other end", b.endHour > a.endHour)
    }

    @Test
    fun `a task with no window is never current and never chimes`() {
        // The common case by a wide margin: most tasks have no window of their
        // own, and a port that defaulted a null window to "open" would put every
        // task the user has ever had on the front page.
        val plain = TaskDto(id = "t1", status = "active")
        assertEquals(false, SyncMath.isCurrentAt(plain, nowMs, zone))
        assertEquals(false, SyncMath.isReminderDueAt(plain, nowMs, zone))
    }

    @Test
    fun `currentAt and dueRemindersAt preserve the order they were given`() {
        // These replace two arrays the server used to send, and the agenda's
        // ordering is the server's business. Re-sorting here would quietly
        // reorder the front page.
        val tasks = listOf(
            TaskDto(id = "a", status = "active", currentFrom = "2026-10-30T09:00:00.000Z"),
            TaskDto(id = "skip", status = "done", currentFrom = "2026-10-30T09:00:00.000Z"),
            TaskDto(id = "b", status = "active", currentFrom = "2026-10-30T08:00:00.000Z"),
        )
        assertEquals(
            listOf("a", "b"),
            SyncMath.currentAt(tasks, nowMs, zone).map { it.id },
        )
    }
}
